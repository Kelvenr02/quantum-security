// Rebuild the offline bundle from the licensed, prepared OGG files.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../assets/audio');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const assets = Object.fromEntries(Object.entries(manifest.files).map(([key, item]) => [key, {
  kind: item.kind,
  data: fs.readFileSync(path.join(root, item.file)).toString('base64')
}]));
fs.writeFileSync(path.join(root, 'bundle.js'), '// Generated by tools/build-audio.cjs. Sources and licenses: assets/audio/CREDITS.md\n' +
  'globalThis.ORBITAL_AUDIO_ASSETS = ' + JSON.stringify(assets) + ';\n');
console.log('Offline audio bundle: ' + Object.keys(assets).length + ' assets.');
